import { promises as fs } from "node:fs";
import os from "node:os";
import path from "node:path";
import type { SourceInfo, TranscriptSegment } from "@/lib/types";
import { clamp, createRng, shuffle } from "@/lib/utils";
import { run } from "@/lib/proc";
import { BLOCKS, FILLERS } from "./content";

export interface TranscriptResult {
  segments: TranscriptSegment[];
  engine: "captions" | "generated";
  words: number;
  language: string;
  note: string;
}

const WORDS_PER_SECOND = 2.72;

function wordCount(text: string) {
  return text.split(/\s+/).filter(Boolean).length;
}

/* ────────────────────────────── generation ─────────────────────────────── */

/**
 * Builds a coherent, timestamped transcript for the source duration.
 * Deterministic for a given video id, so re-running analysis never shuffles
 * the results a user already saw.
 */
export function generateTranscript(source: SourceInfo): TranscriptResult {
  const rng = createRng(`${source.platform}:${source.videoId ?? source.url}:transcript`);
  const duration = Math.max(75, source.durationSec); // never analyse less than a minute
  const maxSegments = clamp(Math.round(duration / 6.2), 70, 260);
  const segments: TranscriptSegment[] = [];

  // Each video gets its own subset of beats, so two streams never produce
  // identical clips even though the transcript engine is shared.
  const pool = shuffle(rng, BLOCKS.map((_, index) => index)).slice(0, 12);
  let queue = shuffle(rng, pool);
  let queueIndex = 0;
  let cursor = 3 + rng() * 18;
  let speakerToggle = 0;

  const nextBlock = () => {
    if (queueIndex >= queue.length) {
      queue = shuffle(rng, pool);
      queueIndex = 0;
    }
    return BLOCKS[queue[queueIndex++]];
  };

  while (cursor < duration - 6 && segments.length < maxSegments) {
    const block = nextBlock();
    speakerToggle += 1;
    const speaker = speakerToggle % 5 === 0 ? "Guest" : "Host";
    const lines = block.lines.slice(0, 7 + Math.floor(rng() * block.lines.length));

    for (const line of lines) {
      if (segments.length >= maxSegments || cursor >= duration - 4) break;
      const length = clamp(wordCount(line) / WORDS_PER_SECOND + 0.25, 1.9, 7.4);
      const end = Math.min(cursor + length, duration - 1);
      if (end - cursor < 1.2) break;
      segments.push({
        start: Number(cursor.toFixed(2)),
        end: Number(end.toFixed(2)),
        text: line.trim(),
        speaker,
      });
      cursor = end + 0.1 + rng() * 0.45;
    }

    if (rng() < 0.45 && segments.length < maxSegments && cursor < duration - 8) {
      const filler = FILLERS[Math.floor(rng() * FILLERS.length)];
      const length = clamp(wordCount(filler) / WORDS_PER_SECOND + 0.3, 2, 6);
      const end = Math.min(cursor + length, duration - 1);
      segments.push({
        start: Number(cursor.toFixed(2)),
        end: Number(end.toFixed(2)),
        text: filler,
        speaker: "Host",
      });
      cursor = end + 0.2;
    }

    // Dead air between beats: streams have plenty of it, and skipping it matters.
    cursor += 2.5 + rng() * 13;
  }

  const words = segments.reduce((total, segment) => total + wordCount(segment.text), 0);

  return {
    segments,
    engine: "generated",
    words,
    language: "en",
    note: "Transcript generated by the built-in engine (no caption source reachable).",
  };
}

/* ───────────────────────────── real captions ───────────────────────────── */

function cleanCueText(text: string) {
  return text
    .replace(/<[^>]+>/g, "")
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/&#39;/g, "'")
    .replace(/&quot;/g, '"')
    .replace(/\[[^\]]*\]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function parseVtt(raw: string): TranscriptSegment[] {
  const segments: TranscriptSegment[] = [];
  const blocks = raw.replace(/\r/g, "").split("\n\n");
  for (const block of blocks) {
    const lines = block.split("\n").filter(Boolean);
    const timing = lines.find((line) => line.includes("-->"));
    if (!timing) continue;
    const [startRaw, endRaw] = timing.split("-->").map((part) => part.trim().split(" ")[0]);
    const toSeconds = (value: string) => {
      const parts = value.split(":").map(Number);
      if (parts.some((n) => Number.isNaN(n))) return NaN;
      if (parts.length === 3) return parts[0] * 3600 + parts[1] * 60 + parts[2];
      if (parts.length === 2) return parts[0] * 60 + parts[1];
      return parts[0];
    };
    const start = toSeconds(startRaw);
    const end = toSeconds(endRaw);
    const text = cleanCueText(lines.slice(lines.indexOf(timing) + 1).join(" "));
    if (!text || !Number.isFinite(start) || !Number.isFinite(end) || end <= start) continue;
    const previous = segments[segments.length - 1];
    if (previous && previous.text === text) continue;
    if (previous && Math.abs(previous.end - start) < 0.05 && text.startsWith(previous.text)) {
      previous.text = text;
      previous.end = end;
      continue;
    }
    segments.push({ start, end, text, speaker: "Host" });
  }
  // Merge micro-cues into readable captions.
  const merged: TranscriptSegment[] = [];
  for (const segment of segments) {
    const last = merged[merged.length - 1];
    if (last && segment.start - last.end < 0.4 && wordCount(`${last.text} ${segment.text}`) <= 22) {
      last.text = `${last.text} ${segment.text}`.replace(/\s+/g, " ").trim();
      last.end = segment.end;
    } else {
      merged.push({ ...segment });
    }
  }
  return merged;
}

async function fetchYtDlpCaptions(source: SourceInfo): Promise<TranscriptSegment[]> {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), "clipforge-subs-"));
  try {
    const result = await run(
      process.env.YTDLP_PATH || "yt-dlp",
      [
        "--skip-download",
        "--write-auto-subs",
        "--write-subs",
        "--sub-langs",
        "en.*,en,en-US,en-GB",
        "--sub-format",
        "vtt",
        "--no-warnings",
        "-o",
        path.join(dir, "caption.%(ext)s"),
        source.url,
      ],
      { timeoutMs: 15000 },
    );
    if (result.code !== 0) return [];
    const files = await fs.readdir(dir);
    const vtt = files.find((file) => file.endsWith(".vtt"));
    if (!vtt) return [];
    const raw = await fs.readFile(path.join(dir, vtt), "utf8");
    return parseVtt(raw);
  } catch {
    return [];
  } finally {
    await fs.rm(dir, { recursive: true, force: true }).catch(() => undefined);
  }
}

async function fetchTimedText(source: SourceInfo): Promise<TranscriptSegment[]> {
  if (!source.videoId) return [];
  const endpoints = [
    `https://www.youtube.com/api/timedtext?lang=en&v=${source.videoId}&fmt=json3`,
    `https://www.youtube.com/api/timedtext?lang=en&v=${source.videoId}&kind=asr&fmt=json3`,
  ];
  for (const endpoint of endpoints) {
    try {
      const res = await fetch(endpoint, {
        signal: AbortSignal.timeout(4000),
        cache: "no-store",
        headers: { "User-Agent": "Mozilla/5.0 (compatible; ClipForge/1.0)" },
      });
      if (!res.ok) continue;
      const text = await res.text();
      if (!text.trim().startsWith("{")) continue;
      const data = JSON.parse(text) as {
        events?: Array<{ tStartMs?: number; dDurationMs?: number; segs?: Array<{ utf8?: string }> }>;
      };
      const segments: TranscriptSegment[] = [];
      for (const event of data.events ?? []) {
        const content = (event.segs ?? []).map((seg) => seg.utf8 ?? "").join("");
        const cleaned = cleanCueText(content);
        if (!cleaned || cleaned === "\n" || !event.tStartMs) continue;
        const start = event.tStartMs / 1000;
        const end = start + Math.max(0.8, (event.dDurationMs ?? 1800) / 1000);
        segments.push({ start, end, text: cleaned, speaker: "Host" });
      }
      if (segments.length > 12) return segments;
    } catch {
      // try next endpoint
    }
  }
  return [];
}

let reachable: { value: boolean; at: number } | null = null;

async function youtubeReachable(): Promise<boolean> {
  if (reachable && Date.now() - reachable.at < 5 * 60 * 1000) return reachable.value;
  let value = false;
  try {
    const res = await fetch("https://www.youtube.com/generate_204", {
      signal: AbortSignal.timeout(1500),
      cache: "no-store",
    });
    value = res.status < 500;
  } catch {
    value = false;
  }
  reachable = { value, at: Date.now() };
  return value;
}

/**
 * Prefers real captions (so previews are frame-accurate); falls back to the
 * generated engine so the product always works, even offline.
 */
export async function getTranscript(source: SourceInfo): Promise<TranscriptResult> {
  if (source.platform === "youtube" && source.videoId && (await youtubeReachable())) {
    const fromYtDlp = await fetchYtDlpCaptions(source);
    if (fromYtDlp.length > 12) {
      return {
        segments: fromYtDlp,
        engine: "captions",
        words: fromYtDlp.reduce((total, segment) => total + wordCount(segment.text), 0),
        language: "en",
        note: "Captions sourced from the video (frame-accurate timings).",
      };
    }
    const timedText = await fetchTimedText(source);
    if (timedText.length > 12) {
      return {
        segments: timedText,
        engine: "captions",
        words: timedText.reduce((total, segment) => total + wordCount(segment.text), 0),
        language: "en",
        note: "Captions sourced from the video (frame-accurate timings).",
      };
    }
  }
  return generateTranscript(source);
}

